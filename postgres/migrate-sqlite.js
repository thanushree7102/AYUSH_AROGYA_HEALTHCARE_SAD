// Non-destructive SQLite -> PostgreSQL data copier. SQLite files are opened read-only.
// Preview: node postgres/migrate-sqlite.js
// Apply:   node postgres/migrate-sqlite.js --apply
require('dotenv').config();
const fs = require('fs');
const path = require('path');
const Database = require('better-sqlite3');
const { pool } = require('./pool');
const map = require('./schema-map.json');
const APPLY = process.argv.includes('--apply');
const root = path.resolve(__dirname, process.env.SQLITE_ROOT || '../shared-database-template');
const ident = (s) => '"' + String(s).replace(/"/g, '""') + '"';
const pgType = (t) => {
  const x = String(t || '').toUpperCase();
  if (x.includes('INT')) return 'BIGINT';
  if (x.includes('CHAR') || x.includes('CLOB') || x.includes('TEXT')) return 'TEXT';
  if (x.includes('BLOB')) return 'BYTEA';
  if (x.includes('REAL') || x.includes('FLOA') || x.includes('DOUB')) return 'DOUBLE PRECISION';
  if (x.includes('BOOL')) return 'BOOLEAN';
  if (x.includes('DATE') || x.includes('TIME')) return 'TIMESTAMPTZ';
  if (x.includes('NUM') || x.includes('DEC')) return 'NUMERIC';
  return 'TEXT';
};
function sqliteFiles(dir) {
  if (!fs.existsSync(dir)) throw new Error(`SQLite source folder not found: ${dir}`);
  const out = [];
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.isFile() && e.name.endsWith('.db')) out.push(p);
    }
  };
  walk(dir);
  return out;
}
async function migrateDb(file) {
  const base = path.basename(file);
  const schema = map[base] || path.basename(path.dirname(file)).replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();
  const db = new Database(file, { readonly: true, fileMustExist: true });
  try {
    const tables = db.prepare("SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all();
    console.log(`\n[${base}] -> schema ${schema} (${tables.length} tables)`);
    if (APPLY) await pool.query(`CREATE SCHEMA IF NOT EXISTS ${ident(schema)}`);
    for (const t of tables) {
      const cols = db.prepare(`PRAGMA table_info(${ident(t.name)})`).all();
      const pks = cols.filter(c => c.pk).sort((a, b) => a.pk - b.pk);
      const defs = cols.map(c => {
        const auto = /INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/i.test(t.sql || '') && c.pk;
        let d = `${ident(c.name)} ${auto ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY' : pgType(c.type)}`;
        if (c.notnull) d += ' NOT NULL';
        if (c.dflt_value !== null && c.dflt_value !== undefined && !auto) d += ` DEFAULT ${String(c.dflt_value)}`;
        return d;
      });
      if (pks.length) defs.push(`PRIMARY KEY (${pks.map(c => ident(c.name)).join(', ')})`);
      const ddl = `CREATE TABLE IF NOT EXISTS ${ident(schema)}.${ident(t.name)} (${defs.join(', ')})`;
      const rows = db.prepare(`SELECT * FROM ${ident(t.name)}`).all();
      console.log(`  ${t.name}: ${cols.length} columns, ${rows.length} rows`);
      if (!APPLY) continue;
      await pool.query(ddl);
      if (!rows.length) continue;
      const names = cols.map(c => c.name);
      const insert = `INSERT INTO ${ident(schema)}.${ident(t.name)} (${names.map(ident).join(',')}) VALUES (${names.map((_, i) => '$' + (i + 1)).join(',')})${pks.length ? ' ON CONFLICT (' + pks.map(c => ident(c.name)).join(', ') + ') DO NOTHING' : ''}`;
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        for (const row of rows) await client.query(insert, names.map(n => row[n] === undefined ? null : row[n]));
        await client.query('COMMIT');
      } catch (e) {
        await client.query('ROLLBACK');
        throw new Error(`${schema}.${t.name}: ${e.message}`);
      } finally { client.release(); }
    }
  } finally { db.close(); }
}
(async () => {
  try {
    const files = sqliteFiles(root);
    console.log(`${APPLY ? 'APPLY MODE' : 'PREVIEW ONLY'} | ${files.length} SQLite files | source: ${root}`);
    if (!files.length) throw new Error('No .db files found in SQLITE_ROOT.');
    for (const f of files) await migrateDb(f);
    console.log(APPLY ? '\nMigration copy finished. SQLite sources were not changed.' : '\nPreview complete. Re-run with --apply to copy data into PostgreSQL.');
  } catch (e) { console.error('Migration stopped:', e.message); process.exitCode = 1; }
  finally { await pool.end().catch(() => {}); }
})();
